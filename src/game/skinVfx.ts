export function getSkinVfxKey(characterId: CharacterId, skinId: SkinId): string {
  return `${characterId}:${skinId}`;
}

export function getSkinVfxProfile(
  characterId: CharacterId,
  skinId: SkinId = 'default'
): SkinVfxProfile {
  return (
    SKIN_VFX_PROFILES[getSkinVfxKey(characterId, skinId)] ??
    SKIN_VFX_PROFILES[getSkinVfxKey(characterId, 'default')] ??
    SKIN_VFX_PROFILES['kuro:default']
  );
}

export function listAllSkinVfxProfiles(): SkinVfxProfile[] {
  return Object.values(SKIN_VFX_PROFILES);
}
